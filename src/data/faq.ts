export const faqByKey = Object.fromEntries(faqGroups.map((g) => [g.key, g])) as Record<
  string,
  FaqGroup
>;

/** ページごとに使うFAQを取り出す */
export function faqItems(...keys: string[]): FaqItem[] {
  return keys.flatMap((k) => faqByKey[k]?.items ?? []);
}
